export function sourceIdForLabel(source?: string, sourceKind?: SourceKind): string | undefined {
  if (!source) return undefined;
  const sourceId = SOURCE_ALIASES[source];
  if (!sourceId) return undefined;
  const catalogSource = SOURCE_CATALOG_BY_ID.get(sourceId);
  return catalogSource && (!sourceKind || catalogSource.kind === sourceKind) ? sourceId : undefined;
}

export function resolveSourceUrl(sourceId?: string, explicitUrl?: string, source?: string, sourceKind?: SourceKind): string | undefined {
  const resolvedId = sourceId ?? sourceIdForLabel(source, sourceKind);
  return explicitUrl ?? (resolvedId ? SOURCE_CATALOG_BY_ID.get(resolvedId)?.url : undefined);
}
